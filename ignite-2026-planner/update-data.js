// Rebuilds data.js from the public Ignite 2026 session catalog.
// Keeps the hand-curated "Hybrid & Infra" ratings and abstracts (the `curated` block in data.js).
//
// Usage:  node update-data.js               (downloads the catalog, needs Node 18+)
//         node update-data.js catalog.json  (uses a saved copy of the API response)
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const API = "https://ignite.microsoft.com/api/session/all/en-US";
const OUT = path.join(__dirname, "data.js");
const ABSTRACT_MAX = 320;

function readCurated() {
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(OUT, "utf8"), ctx);
  const D = ctx.window.IGNITE || {};
  if (D.curated) return D.curated;
  // first run: old format with a `sessions` array carrying stars
  const c = {};
  (D.sessions || []).filter(s => s.stars).forEach(s => { c[s.code] = { stars: s.stars, abstract: s.abstract }; });
  return c;
}

const strip = h => String(h || "")
  .replace(/<[^>]+>/g, " ")
  .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'")
  .replace(/[​‌‍﻿]/g, "")
  .replace(/Seating for this session is first-come, first-served\..*$/i, "")
  .replace(/\s+/g, " ").trim();
const short = t => {
  if (t.length <= ABSTRACT_MAX) return t;
  const cut = t.slice(0, ABSTRACT_MAX);
  return cut.slice(0, cut.lastIndexOf(" ")).replace(/[,;:.\s]+$/, "") + " …";
};
const dv = v => [].concat(v || []).map(x => (x && (x.displayValue || x.logicalValue)) || "").filter(Boolean);

(async () => {
  const src = process.argv[2];
  const raw = src
    ? JSON.parse(fs.readFileSync(src, "utf8"))
    : await (await fetch(API, { headers: { "User-Agent": "Mozilla/5.0" } })).json();
  const list = Array.isArray(raw) ? raw : (raw.data || raw.sessions || []);
  if (!list.length) throw new Error("No sessions found in the catalog response.");

  const curated = readCurated();
  const rows = list
    .filter(s => s.sessionCode && s.title)
    .map(s => ({
      code: s.sessionCode.trim(),
      title: strip(s.title),
      type: dv(s.sessionType)[0] || "",
      level: (dv(s.sessionLevel)[0] || "").replace(/^\((\d+)\).*$/, "$1"),
      start: s.startDateTime || null,
      end: s.endDateTime || null,
      speakers: strip(s.speakerNames),
      location: dv(s.location)[0] || "",
      abstract: short(strip(s.description)),
    }));

  // drop exact duplicates, then give repeated sessions a unique id per time slot
  const seen = new Set();
  const uniq = rows.filter(r => { const k = r.code + "|" + r.start; if (seen.has(k)) return false; seen.add(k); return true; });
  const t = r => (r.start ? Date.parse(r.start) : Infinity);
  uniq.sort((a, b) => t(a) - t(b) || a.code.localeCompare(b.code));
  const count = {}, idx = {};
  uniq.forEach(r => { count[r.code] = (count[r.code] || 0) + 1; });
  uniq.forEach(r => {
    idx[r.code] = (idx[r.code] || 0) + 1;
    r.id = count[r.code] > 1 ? `${r.code}-${idx[r.code]}` : r.code;
    if (count[r.code] > 1) r.repeat = `${idx[r.code]}/${count[r.code]}`;
  });

  const missing = Object.keys(curated).filter(c => !uniq.some(r => r.code === c));
  const today = new Date().toISOString().slice(0, 10);
  const line = r => "    " + JSON.stringify({ id: r.id, code: r.code, title: r.title, type: r.type, level: r.level, start: r.start, end: r.end, speakers: r.speakers, location: r.location, abstract: r.abstract, ...(r.repeat ? { repeat: r.repeat } : {}) });
  const cur = Object.entries(curated)
    .sort((a, b) => b[1].stars - a[1].stars || a[0].localeCompare(b[0]))
    .map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`);

  const js = `// Microsoft Ignite 2026 (San Francisco, 16–20 Nov 2026) — session data for the planner.
// Times are UTC (ISO 8601). start/end = null means on-demand.
//
// \`curated\` is edited by hand: the "Hybrid & Infra" picks.
//   stars: 3 = must-see, 2 = highly relevant, 1 = background / partner
//   abstract: optional short summary that replaces the catalog text
// \`sessions\` is generated by update-data.js from ${API}
// Do not edit \`sessions\` by hand; run \`node update-data.js\` to refresh it.
window.IGNITE = {
  event: "Microsoft Ignite 2026",
  eventTimeZone: "America/Los_Angeles",
  catalogUrl: "https://ignite.microsoft.com/en-US/sessions",
  dataAsOf: "${today}",

  curated: {
${cur.join(",\n")}
  },

  sessions: [
${uniq.map(line).join(",\n")}
  ]
};
`;
  fs.writeFileSync(OUT, js, "utf8");
  console.log(`data.js written: ${uniq.length} session slots (${Object.keys(count).length} unique codes), ${Object.keys(curated).length} curated, ${(js.length / 1024).toFixed(0)} KB`);
  if (missing.length) console.warn("Curated codes not found in catalog:", missing.join(", "));
})().catch(e => { console.error(e.message); process.exit(1); });
